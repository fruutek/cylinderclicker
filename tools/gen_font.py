def g(ch, text):
    rows = [r for r in text.strip("\n").split("\n")]
    w = max(len(r) for r in rows)
    rows = [r.ljust(w, ".") for r in rows]
    while len(rows) < ROWS:
        rows.append("." * w)
    G[ch] = rows


