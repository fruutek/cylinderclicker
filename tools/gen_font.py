def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    tex_w, tex_h = 128, 80
    img = Image.new("RGBA", (tex_w, tex_h), (0, 0, 0, 0))
    x = y = 0
    lines = []
    for ch, rows in G.items():
        w = len(rows[0])
        if x + w + 1 > tex_w:
            x = 0
            y += ROWS + 1
        for ry, row in enumerate(rows):
            for rx, c in enumerate(row):
                if c == "#":
                    img.putpixel((x + rx, y + ry), (255, 255, 255, 255))
        lines.append(
            "char id=%d x=%d y=%d width=%d height=%d xoffset=0 yoffset=0 xadvance=%d page=0 chnl=15"
            % (ord(ch), x, y, w, ROWS, w + 1)
        )
        x += w + 1
    assert y + ROWS <= tex_h, "font texture too small"
    img.save(os.path.join(OUT_DIR, "pixel.png"))
    with open(os.path.join(OUT_DIR, "pixel.fnt"), "w") as f:
        f.write('info face="CylinderPixel" size=8 bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0\n')
        f.write("common lineHeight=%d base=%d scaleW=%d scaleH=%d pages=1 packed=0\n" % (LINE_HEIGHT, BASELINE, tex_w, tex_h))
        f.write('page id=0 file="pixel.png"\n')
        f.write("chars count=%d\n" % len(lines))
        f.write("\n".join(lines) + "\n")
    print("font: %d glyphs" % len(lines))


if __name__ == "__main__":
    main()
